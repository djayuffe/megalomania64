#!/usr/bin/env python3
"""Generate src/tables.asm: SID music for four tunes + title raster-bar tables.
Pure Python, deterministic. PAL SID clock 985248 Hz: reg = f * 2^24 / clock."""
import math
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
CLOCK=985248
NAMES={'C':-9,'C#':-8,'D':-7,'D#':-6,'E':-5,'F':-4,'F#':-3,'G':-2,'G#':-1,'A':0,'A#':1,'B':2}
def reg(note):
    name,octave=note[:-1],int(note[-1])
    semis=NAMES[name]+12*(octave-4)
    f=440.0*2**(semis/12)
    return round(f*16777216/CLOCK)
TUNES=[
 ('ancient',14,
  'E4 G4 A4 G4 E4 D4 C4 D4 E4 G4 A4 C5 B4 A4 G4 E4',
  'A2 A2 A2 A2 D3 D3 D3 D3 A2 A2 E3 E3 A2 A2 A2 A2'),
 ('medieval',12,
  'D4 F4 A4 G4 F4 E4 D4 F4 G4 A4 C5 A4 G4 F4 E4 D4',
  'D2 D2 A2 A2 C3 C3 G2 G2 D2 D2 F2 F2 G2 A2 A2 D2'),
 ('industrial',9,
  'E4 G4 B4 E5 D5 B4 G4 B4 C5 E5 G5 E5 B4 A4 G4 F#4',
  'E2 E2 E2 E2 G2 G2 G2 G2 C3 C3 C3 C3 B2 B2 B2 B2'),
 ('title',10,
  'C4 E4 G4 C5 B4 G4 E4 G4 A4 C5 E5 C5 G4 B4 D5 G4',
  'C2 G2 C2 G2 G2 D3 G2 D3 A2 E3 A2 E3 G2 D3 G2 G2'),
 ('victory',7,
  'C4 E4 G4 C5 G4 C5 E5 G5 E5 C5 G4 C5 E5 G5 C6 C6',
  'C2 C2 C3 C3 G2 G2 C3 C3 F2 F2 G2 G2 C3 C3 C3 C3'),
 ('defeat',15,
  'A4 G4 F4 E4 D4 C4 B3 A3 E4 D4 C4 B3 A3 G3 E3 A3',
  'A2 A2 A2 A2 F2 F2 E2 E2 D2 D2 E2 E2 A1 A1 A1 A1'),
]
out=['; GENERATED by tools/gen_tables.py - do not edit by hand','']
def table(label,vals):
    for i in range(0,len(vals),16):
        out.append((f'{label}: ' if i==0 else '')+'!byte '+','.join(str(v) for v in vals[i:i+16]))
mel=[];bas=[]
for name,tempo,m,b in TUNES:
    mn=m.split();bn=b.split();assert len(mn)==16==len(bn),name
    mel+=[reg(n) for n in mn];bas+=[reg(n) for n in bn]
assert all(0<v<65536 for v in mel+bas)
table('melody_lo',[v&255 for v in mel]);table('melody_hi',[v>>8 for v in mel])
table('bass_lo',[v&255 for v in bas]);table('bass_hi',[v>>8 for v in bas])
out.append('music_tempo: !byte '+','.join(str(t[1]) for t in TUNES))
out.append('music_variant: !byte 0,0,0,0,1,1,1,2,2,2   ; epoch 0..9 -> tune')
# raster bars: 16 colours (rainbow), wobble table for the first bar line
BARS=[6,14,3,1,3,14,6,0, 0,6,14,3,1,3,14,6]
BARS=[2,10,7,1,7,10,2,9, 9,2,10,7,1,7,10,2]
out.append('bar_color: !byte '+','.join(map(str,BARS)))
wave=[63+round(8*math.sin(2*math.pi*i/32)) for i in range(32)]
out.append('bar_wave: !byte '+','.join(map(str,wave)))
out.append('crow_lo: !byte '+','.join(str((0xD800+r*40)&255) for r in range(25)))
out.append('crow_hi: !byte '+','.join(str((0xD800+r*40)>>8) for r in range(25)))
(ROOT/'src/tables.asm').write_text('\n'.join(out)+'\n')
print('wrote src/tables.asm')
